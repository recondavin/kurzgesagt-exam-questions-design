# Writes eng/eng-paper.css: English on exam paper (the user, of the dark English pages: "why does it look like this",
# "you know how it should look"), the look of English's own Compare it page and of geography.html: cream paper, the
# paper's ink, Outfit. It loads after bio/bio-shell.css and eng/eng.css and only overrides:
#   - the shell's colour tokens (ground, surfaces, rules, ink, muted, faint) for body.eng, so everything that uses them flips;
#   - every rule in those two files that sets light text (#fff and the pale greys) on no background or a token surface:
#     the same selector under body.eng gets the ink instead (light text on a coloured button or tile is left alone);
#   - every rule that paints a dark hard-coded background: paper or a card instead;
#   - fonts: Fredoka and Nunito become Outfit (Lexend on the paper and Caveat for the pen stay).
# The pages already on paper or in the cinema look (Compare it's strip .cpx / body.eng-papertop, Read it through
# .eng-read, the cinema .eng-cine) are skipped: they keep their own colours.
# Usage: python3 tools/eng/build_paper_theme.py
import os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SKIP = re.compile(r'eng-papertop|\.cpx|eng-read|eng-cine|cine-|\.tch|\.am-|\.tb-|\.mg-|\.pl-|\.ar-|bio-logo|\.bh-|\.pg-|\.ld-|\.dy-')
LIGHT = {'#fff': '#13233A', '#ffffff': '#13233A', '#fffdf6': '#13233A', '#e3ebef': '#13233A', '#f1f7fb': '#13233A',
         '#dce6eb': '#2E3A4A', '#ffe45c': '#7A5A00', '#ffe14d': '#7A5A00', '#8ce65a': '#2E7D12', '#8be07a': '#2E7D12', '#c6f0b4': '#2E7D12', '#c9d4da': '#3E4A5A', '#9fb0ba': '#515D6E', '#b9c7cf': '#515D6E', '#93a5ae': '#6B7480'}
DARK_BG = {'#0f1a1f': '#FFFDF8', '#131f24': '#F7F2E4', '#1a2b32': '#FFFDF8', '#22343c': '#ECE5D1', '#2b3b42': '#E3DAC2',
           '#101a1e': '#E3DAC2', '#1a2b33': '#ECE5D1', '#162329': '#FFFDF8', '#1d2f37': '#FFFDF8'}
# the phone feed (Compare it on phones), the scene player's pause screen and the story player stay dark (the user, of
# the pause screen in paper colours: "i can barely read this"): only their fonts change
DARK_KEEP = re.compile(r'\.eng-fi|eng-feed|\.eng-rail|\.eng-pause|\.eng-story')
NEUTRAL_BG = re.compile(r'^(none|transparent|var\(--(surface|raised|active|ground|control)\)|#(0f1a1f|131f24|1a2b32|22343c|2b3b42|162329|1d2f37))', re.I)

def rules(css):
    """(media or '', selector, body) for every plain rule, one level of @media deep."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    out, i, n = [], 0, len(css)
    def block(text, media):
        for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', text):
            sel = m.group(1).strip()
            if sel.startswith('@') or not sel: continue
            out.append((media, sel, m.group(2)))
    pos = 0
    for m in re.finditer(r'@media[^{]+\{', css):
        if m.start() < pos: continue
        block(css[pos:m.start()], '')
        depth, j = 1, m.end()
        while depth and j < n:
            depth += {'{': 1, '}': -1}.get(css[j], 0); j += 1
        block(css[m.end():j - 1], m.group(0)[:-1].strip())
        pos = j
    block(css[pos:], '')
    return out

def decl(body, prop):
    m = re.findall(r'(?:^|;)\s*' + prop + r'\s*:\s*([^;]+)', body)
    return m[-1].replace('!important', '').strip() if m else None

def scope(sel):
    parts = []
    for s in sel.split(','):
        s = s.strip()
        if not s: continue
        if s.startswith('body.eng'): parts.append(s)
        elif s.startswith('body'): parts.append('body.eng' + s[4:])
        elif s.startswith(':root'): continue
        else: parts.append('body.eng ' + s)
    return ', '.join(parts)

out = ['/* Generated by tools/eng/build_paper_theme.py: English on exam paper. Do not edit by hand. */',
       'body.eng { --ground: #F7F2E4; --surface: #FFFDF8; --raised: #ECE5D1; --active: #E3DAC2; --rule: #D6CDB5; --control: #C8BFA8;',
       '  --ink: #13233A; --muted: #515D6E; --faint: #6B7480; background: #F7F2E4; color: #13233A; }',
       'body.eng .sh-top { border-bottom-color: #D6CDB5; }',
       'body.eng .eng-card, body.eng .eng-step, body.eng .eng-pick { box-shadow: inset 0 0 0 1px #D6CDB5; }',
       'body.eng .eng-pick.is-on { border-color: #13233A; }',
       'body.eng .eng-btn--quiet { box-shadow: 0 3px 0 #C8BFA8; }',
       # text that takes white from a parent or a later rule
       'body.eng .eng-who__trait, body.eng .q-def.q-word, body.eng .q-nw, body.eng .eng-crit__c, body.eng .eng-sec__m { color: #13233A; }',
       'body.eng .eng-beat--quote, body.eng .eng-beat--quote q { color: #13233A; }',
       'body.eng .eng-q__plain b { color: #7A5A00; }',
       # headings as on Compare it: Outfit at its heaviest, the ink
       'body.eng .cv-h1 { font-weight: 800 !important; letter-spacing: -.02em; }',
       'body.eng .eng-app h2.eng-h2 { font-weight: 800; letter-spacing: -.01em; }',
       'body.eng .eng-card h3, body.eng .eng-step h3, body.eng .eng-part h3, body.eng .eng-pick__t, body.eng .ebd-tile h3 { font-weight: 700; }',
       # the Compare it card's first letters were under its colour bar
       'body.eng .eng-cp__home { display: block; padding-left: 28px; }',
       'body.eng .eng-quick { display: flex; flex-wrap: wrap; gap: 10px; margin: 0; }']
seen = set()
for f in ('bio/bio-shell.css', 'eng/eng.css'):
    for media, sel, body in rules(open(os.path.join(ROOT, f)).read()):
        if SKIP.search(sel): continue
        sc = scope(sel)
        if not sc: continue
        add = []
        keep = bool(DARK_KEEP.search(sel))
        col, bg = decl(body, 'color'), decl(body, 'background') or decl(body, 'background-color')
        if not keep and col and col.lower() in LIGHT and (bg is None or NEUTRAL_BG.match(bg)):
            add.append('color: ' + LIGHT[col.lower()] + ' !important')
        if not keep and bg and bg.split()[0].lower() in DARK_BG:
            add.append('background: ' + DARK_BG[bg.split()[0].lower()])
        # pale washes and rules drawn in white on the dark page: the same in the ink on paper
        for prop in ('background', 'background-color', 'border', 'border-color', 'border-top', 'border-bottom', 'border-left', 'border-right', 'box-shadow', 'outline'):
            v = decl(body, prop)
            if not keep and v and re.search(r'rgba\(255, ?255, ?255, ?\.?\d', v) and not (prop.startswith('background') and col and col.lower() in ('#fff', '#ffffff')):
                add.append(prop + ': ' + re.sub(r'rgba\(255, ?255, ?255,', 'rgba(19, 35, 58,', v))
        font = decl(body, 'font') or decl(body, 'font-family') or ''
        if re.search(r'Fredoka|Nunito', font) and not re.search(r'Caveat|Lexend', font):
            add.append("font-family: Outfit, system-ui, -apple-system, 'Segoe UI', sans-serif")
        if not add: continue
        line = sc + ' { ' + '; '.join(add) + '; }'
        if (media, line) in seen: continue
        seen.add((media, line))
        out.append((media + ' { ' + line + ' }') if media else line)
open(os.path.join(ROOT, 'eng', 'eng-paper.css'), 'w').write('\n'.join(out) + '\n')
print(len(out), 'lines')
