"""Builds bio/d<chapter>.js: the Biology exam diagrams, in the Draw it format (480 x 320, flat, side-on).

Each chapter's diagrams are drawn in tools/bio/chapters/ch<N>.py (MAKERS), with the helpers in bio_art.py.
Each diagram goes into window.ExamDrawDiagrams['bio-<chapter>'] so Draw it can use it, and into
window.BioArt[<id>] with:
  plain    the art with no labels (exam questions put their own letters on it),
  anchors  where each structure is, by name (exam-question letters and Build it pins go there),
  parts    the data-part groups in build order, named (Build it drags these into place).
Labels carry data-label, keys (words that count when you name it) and tag (the words on its pill).
A chapter can also have CHAIN_ART: {chain title: svg}, the Chain reaction pictures (400 x 300, drawn with the
step/until/badge helpers in tools/mini_games/build_game_art.py), which go into window.ExamGameArt.chains['bio-<chapter>'].
Run: python3 tools/bio/build_bio_diagrams.py [chapter ...]   (no chapter: all of them)
"""
import importlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)


def chapters(wanted):
    found = sorted(int(f[2:-3]) for f in os.listdir(os.path.join(HERE, 'chapters')) if f.startswith('ch') and f.endswith('.py'))
    return [n for n in found if not wanted or n in wanted]


def build(ch):
    mod = importlib.import_module('chapters.ch%d' % ch)
    ds = [m() for m in mod.MAKERS]
    draw = {'subject': 'biology', 'topic': mod.TOPIC,
            'diagrams': [{k: d[k] for k in ('id', 'name', 'say', 'tip', 'labels', 'svg')} for d in ds]}
    art = {d['id']: {'chapter': ch, 'name': d['name'], 'plain': d['plain'], 'anchors': d['anchors'], 'parts': d['parts'], 'labels': d['labels']}
           for d in ds}
    out = os.path.join(HERE, '..', '..', 'bio', 'd%d.js' % ch)
    with open(out, 'w') as f:
        f.write('// Generated by tools/bio/build_bio_diagrams.py from tools/bio/chapters/ch%d.py: the chapter\'s exam diagrams.\n' % ch)
        f.write('// Swap any svg for your own art: keep data-part (build order), data-label (label order) and the anchors.\n')
        f.write('window.ExamDrawDiagrams = window.ExamDrawDiagrams || {};\n')
        f.write('window.ExamDrawDiagrams[' + json.dumps('bio-%d' % ch) + '] = ' + json.dumps(draw, ensure_ascii=False, indent=1) + ';\n')
        f.write('window.BioArt = window.BioArt || {};\n')
        for k, v in art.items():
            f.write('window.BioArt[' + json.dumps(k) + '] = ' + json.dumps(v, ensure_ascii=False, indent=1) + ';\n')
        chain_art = getattr(mod, 'CHAIN_ART', None)
        if chain_art:
            chain_art = chain_art() if callable(chain_art) else chain_art
            f.write('window.ExamGameArt = window.ExamGameArt || {};\nwindow.ExamGameArt.chains = window.ExamGameArt.chains || {};\n')
            f.write('window.ExamGameArt.chains[' + json.dumps('bio-%d' % ch) + '] = ' + json.dumps(chain_art, ensure_ascii=False, indent=1) + ';\n')
    print('wrote', os.path.normpath(out), len(ds), 'diagrams:', ', '.join(d['id'] for d in ds))


def main():
    for ch in chapters([int(a) for a in sys.argv[1:]]):
        build(ch)


if __name__ == '__main__':
    main()
