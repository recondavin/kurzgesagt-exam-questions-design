"""Builds bio/sprint.js, Label sprint's diagrams: the real ones from the exam papers, from the checked lists in
tools/bio/sprint/ch<N>.json. Each is a list of {ch, q, img, box, cover, spots}: the page image, the box shown and the
printed names covered ([x, y, width, height] in % of the page; a fifth item is the cover's colour when the
name is printed on grey, not white), and the spots to tap ({t: name, at: [x, y]},
on the structure itself; names from the marking schemes). Run: python3 tools/bio/build_bio_sprint.py
"""
import json, os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'bio', 'sprint.js')


def source(q):
    if q.startswith('S1-') or q.startswith('S2-'):
        return 'From sample paper ' + q[1]
    return 'From the ' + q[:4] + ' exam paper'


def clip(c, b):
    # A cover only matters inside the box: cut to it (None when it's all outside).
    x1, y1 = max(c[0], b[0]), max(c[1], b[1])
    x2, y2 = min(c[0] + c[2], b[0] + b[2]), min(c[1] + c[3], b[1] + b[3])
    return [round(x1, 2), round(y1, 2), round(x2 - x1, 2), round(y2 - y1, 2)] if x2 > x1 and y2 > y1 else None


def tint(img, c):
    # A printed name on a grey organ or body is covered in that grey, not a white box: the middle colour of the pixels
    # just around the cover. Plain white is left out (the default).
    w, h = img.size
    x1, y1, x2, y2 = [int(round(v)) for v in (c[0] * w / 100, c[1] * h / 100, (c[0] + c[2]) * w / 100, (c[1] + c[3]) * h / 100)]
    ring = [(x, y) for x in range(x1 - 3, x2 + 3) for y in (y1 - 3, y2 + 2)] + [(x, y) for y in range(y1, y2) for x in (x1 - 3, x2 + 2)]
    px = [img.getpixel((min(max(x, 0), w - 1), min(max(y, 0), h - 1))) for x, y in ring]
    mid = [sorted(p[i] for p in px)[len(px) // 2] for i in range(3)]
    return None if min(mid) >= 245 else '#%02X%02X%02X' % tuple(mid)


def main():
    data = {}
    for ch in (28, 29, 30, 31, 32):
        path = os.path.join(HERE, 'sprint', 'ch%d.json' % ch)
        if not os.path.exists(path):
            continue
        data[ch] = []
        for d in json.load(open(path)):
            img = Image.open(os.path.join(HERE, '..', '..', d['img'])).convert('RGB')
            cover = [c for c in (clip(c, d['box']) for c in d.get('cover', [])) if c]
            cover = [c + [tint(img, c)] if tint(img, c) else c for c in cover]
            data[ch].append({'q': d['q'], 'src': source(d['q']), 'img': d['img'], 'box': d['box'], 'cover': cover,
                             'spots': [{'t': s['t'], 'at': [round(v, 2) for v in s['at']]} for s in d['spots']]})
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/bio/build_bio_sprint.py from tools/bio/sprint/ch<N>.json: Label sprint\'s diagrams, cut from\n')
        f.write('// the real exam papers (bio-quick.js), with their printed names covered and a spot on each part.\n')
        f.write('window.BioSprint = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print({ch: '%d diagrams, %d spots' % (len(v), sum(len(d['spots']) for d in v)) for ch, v in data.items()})


if __name__ == '__main__':
    main()
