"""Builds bio/taboo.js: the terms of "Don't Say It" (bio/bio-quizgames.js), where the student describes a term without
saying it or its banned words and the examiner guesses it when the description has enough of its ideas. Written per
chapter in tools/bio/taboo/ch<N>.json ([{term, ban, ideas: [{a, k}], need, model}]); this checks their shape and writes
the site's file. tools/bio/tests/taboo.mjs checks they work (the model passes, vague descriptions and the other terms'
models don't).
Run: python3 tools/bio/build_bio_taboo.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))


def main():
    problems = 0
    out = {}
    for ch in (28, 29, 30, 31, 32):
        src = os.path.join(HERE, 'taboo', 'ch%d.json' % ch)
        if not os.path.exists(src):
            print('ch%d: no terms yet' % ch)
            problems += 1
            continue
        terms = json.load(open(src))
        for t in terms:
            at = 'ch%d %s' % (ch, t.get('term'))
            ban, ideas = t.get('ban') or [], t.get('ideas') or []
            if not t.get('term') or not 3 <= len(ban) <= 5 or not all(isinstance(b, str) and b and ' ' not in b for b in ban):
                print('%s: needs a term and 3 to 5 single banned words' % at)
                problems += 1
            if not 2 <= len(ideas) <= 4 or not all(i.get('a') and i.get('k') for i in ideas):
                print('%s: needs 2 to 4 ideas, each with its text and keys' % at)
                problems += 1
            if not 1 <= t.get('need', 0) <= len(ideas) or not t.get('model') or len(t['model']) > 200:
                print('%s: need or model wrong' % at)
                problems += 1
        out[ch] = [{'term': t['term'], 'ban': t['ban'], 'ideas': t['ideas'], 'need': t['need'], 'model': t['model']} for t in terms]
    if problems:
        print('%d problems; bio/taboo.js not written' % problems)
        sys.exit(1)
    with open(os.path.join(ROOT, 'bio', 'taboo.js'), 'w') as f:
        f.write('// Generated by tools/bio/build_bio_taboo.py from tools/bio/taboo/ch<N>.json: the terms of Don\'t Say It.\n')
        f.write('window.BioTaboo = %s;\n' % json.dumps(out, ensure_ascii=False, separators=(',', ':')))
    print('wrote bio/taboo.js: %s' % ', '.join('ch%d %d terms' % (ch, len(out[ch])) for ch in out))


if __name__ == '__main__':
    main()
