"""Builds bio/checks<N>.js: one quick check per part of every exam question, shown at the end of that part's slide in
the desk guide (bio/bio-desk.js): a short question, the right answer, three believable wrong ones (or one for true or
false), why, and a hint the examiner gives first when asked for help on the part (before the answer). Written per chapter in tools/bio/checks/ch<N>.json ({question id: [one check per part]}), from the
marking schemes; this checks them (one per part, lengths, the right answer not among the wrong ones) and writes the
site's files.
Run: python3 tools/bio/build_bio_checks.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))


def main():
    problems = 0
    for ch in (28, 29, 30, 31, 32):
        src = os.path.join(HERE, 'checks', 'ch%d.json' % ch)
        if not os.path.exists(src):
            print('ch%d: no checks yet' % ch)
            continue
        checks = json.load(open(src))
        questions = json.load(open(os.path.join(HERE, 'questions', 'ch%d.json' % ch)))['questions']
        out = {}
        for q in questions:
            got = checks.get(q['id'])
            if not got or len(got) != len(q['parts']):
                print('ch%d %s: %s checks for %d parts' % (ch, q['id'], len(got) if got else 'no', len(q['parts'])))
                problems += 1
                continue
            for k, c in enumerate(got):
                tf = c['right'] in ('True', 'False')
                bad = [m for m, ok in (('question too long', len(c['q']) <= 110), ('right answer too long', len(c['right']) <= 70),
                                       ('wrong answers', len(c['wrong']) == (1 if tf else 3)), ('right among wrong', c['right'] not in c['wrong']),
                                       ('a wrong answer too long', all(len(w) <= 70 for w in c['wrong'])), ('why too long', len(c['why']) <= 160),
                                       ('hint too long', len(c.get('hint', '')) <= 100),
                                       ('hint gives the answer', not (c.get('hint') and len(c['right']) < 30 and c['right'] not in ('True', 'False') and c['right'].lower() in c['hint'].lower()))) if not ok]
                if bad:
                    print('ch%d %s part %d: %s' % (ch, q['id'], k + 1, ', '.join(bad)))
                    problems += 1
            out[q['id']] = [dict({'q': c['q'], 'right': c['right'], 'wrong': c['wrong'], 'why': c['why']}, **({'hint': c['hint']} if c.get('hint') else {})) for c in got]
        with open(os.path.join(ROOT, 'bio', 'checks%d.js' % ch), 'w') as f:
            f.write('// Generated by tools/bio/build_bio_checks.py from tools/bio/checks/ch%d.json: one quick check per part.\n' % ch)
            f.write('window.BioChecks = window.BioChecks || {};\nwindow.BioChecks[%d] = %s;\n' % (ch, json.dumps(out, ensure_ascii=False, separators=(',', ':'))))
        print('ch%d: %d questions, %d checks' % (ch, len(out), sum(len(v) for v in out.values())))
    sys.exit(1 if problems else 0)


if __name__ == '__main__':
    main()
