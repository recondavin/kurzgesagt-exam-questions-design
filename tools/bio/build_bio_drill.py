"""Builds bio/drill.js: Exam drill's new questions (bio/bio-drill.js), on the parts of the course no exam has asked yet,
written in the exam's style with their own scheme points. Written per chapter in tools/bio/drill/ch<N>.json
([{id, topic, q, marks, need, pts: [{a, accept, k}], right, wrong, why}]); tools/bio/tests/drill.mjs checks them (the
right box gets full marks, no wrong one does). The drill's real exam questions and diagrams come from the papers'
quick checks and Label sprint at run time.
Run: python3 tools/bio/build_bio_drill.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))


def main():
    out, missing = {}, []
    for ch in (28, 29, 30, 31, 32):
        src = os.path.join(HERE, 'drill', 'ch%d.json' % ch)
        if not os.path.exists(src):
            missing.append(ch)
            continue
        out[ch] = [{k: it[k] for k in ('id', 'topic', 'q', 'marks', 'need', 'pts', 'right', 'wrong', 'why')} for it in json.load(open(src))]
    if missing:
        print('no new questions yet for chapter %s' % ', '.join(map(str, missing)))
    with open(os.path.join(ROOT, 'bio', 'drill.js'), 'w') as f:
        f.write('// Generated by tools/bio/build_bio_drill.py from tools/bio/drill/ch<N>.json: Exam drill\'s new questions.\n')
        f.write('window.BioDrillNew = %s;\n' % json.dumps(out, ensure_ascii=False, separators=(',', ':')))
    print('wrote bio/drill.js: %s' % ', '.join('ch%d %d' % (ch, len(out[ch])) for ch in out))
    sys.exit(1 if missing else 0)


if __name__ == '__main__':
    main()
